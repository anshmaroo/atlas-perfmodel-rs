#!/usr/bin/env python3
"""Generate tests/data/isa_golden.txt from the Python performance model (npu_model).

Run from this repository's root with the Python model's virtualenv:

    <npu_model>/.venv/bin/python -B scripts/gen_isa_golden.py <npu_model> > tests/data/isa_golden.txt

Line formats:

    spec <mnemonic> <format> <exu> <functional 0|1> <match> <mask> [<operand>:<access> ...]
    enc  <mnemonic> <word> [<operand>=<value> ...]

`spec` lines come from `npu_model.isa_metadata.export_isa()`. `enc` lines encode operand vectors
through `isa_metadata._encode`. Each instruction gets several vectors:

- values are pairwise distinct, so a swapped field is caught;
- values sit at the type boundaries. That includes m63, which the Rust model rejects for
  register-pair operands (only m63; it accepts odd pairs such as m61);
- signed/unsigned immediate aliases (e.g. -1 and 4095) must give the same word.
"""

import subprocess
import sys
from pathlib import Path


def main() -> None:
    root = Path(sys.argv[1]).resolve()
    sys.path.insert(0, str(root))

    from npu_model.isa import IsaSpec, UJType
    from npu_model.isa_metadata import _encode, _fields, export_isa
    from npu_model.isa_types import (
        Accumulator,
        Channel,
        ExponentReg,
        MatrixReg,
        SBImm12,
        ScalarReg,
        WeightBuffer,
    )

    wide = {ScalarReg: (1, 31, (13, 20, 27, 4)), ExponentReg: (1, 31, (7, 19)), Channel: (1, 7, (3, 5))}
    one_bit = (Accumulator, WeightBuffer)

    def vectors(cls):
        fields = [(f.repr, f.inner) for f in _fields(cls)]
        even = lambda inner: inner is SBImm12 or issubclass(cls, UJType)

        def imm_bits(inner):
            return 21 if issubclass(cls, UJType) else (inner.upper_bound - 1).bit_length()

        def build(style):
            counts: dict[object, int] = {}
            values = {}
            for name, inner in fields:
                group = "1bit" if inner in one_bit else inner
                i = counts.get(group, 0)
                counts[group] = i + 1
                if inner in one_bit:
                    values[name] = [1, 0][i] if style != "high" else [0, 1][i]
                elif inner is MatrixReg:
                    values[name] = {
                        "high": (62, 60, 58),
                        "odd": (63, 61, 59),
                        "odd2": (61, 63, 59),
                    }.get(style, (2, 4, 6))[i]
                elif inner in wide:
                    low, high, odd = wide[inner]
                    values[name] = {"high": high - i, "odd": odd[i], "odd2": odd[-1 - i]}.get(style, low + i)
                else:  # immediate
                    step = 2 if even(inner) else 1
                    signed = inner.lower_bound < 0
                    values[name] = {
                        "low": inner.lower_bound,
                        "high": inner.upper_bound - step,
                        "odd": -2 if signed else 21,
                        "odd2": 2,
                        "alias_s": -step if signed else None,
                        "alias_u": (1 << imm_bits(inner)) - step if signed else None,
                    }[style]
                    if values[name] is None:
                        return None
            return values

        seen = []
        for style in ("low", "high", "odd", "odd2", "alias_s", "alias_u"):
            values = build(style)
            if values is not None and values not in seen:
                seen.append(values)
        return seen

    rev = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    out = [
        f"# Generated by scripts/gen_isa_golden.py from npu_model {rev or 'unknown'}. Do not edit by hand.",
        "# spec <mnemonic> <format> <exu> <functional> <match> <mask> [<operand>:<access> ...]",
        "# enc  <mnemonic> <word> [<operand>=<value> ...]",
    ]
    skipped = []
    for info in export_isa()["instructions"]:
        mnemonic = info["mnemonic"]
        cls = IsaSpec.operations[mnemonic]
        enc = info["encoding"]
        operands = [f for p in info["operands"] for f in p["fields"]]
        out.append(" ".join([
            "spec", mnemonic, info["format"].removesuffix("Type"), cls.exu.name,
            str(int(info["functional_supported"])), f"0x{enc['match']:08x}", f"0x{enc['mask']:08x}",
            *(f"{f['name']}:{f['access']}" for f in operands),
        ]))
        for values in vectors(cls):
            try:
                word = _encode(cls, **values) & 0xFFFFFFFF
            except Exception as err:  # outside what the Python constructors accept
                skipped.append(f"{mnemonic} {values}: {err}")
                continue
            out.append(" ".join(["enc", mnemonic, f"0x{word:08x}", *(f"{k}={v}" for k, v in values.items())]))
    print("\n".join(out))
    for line in skipped:
        print(f"skipped {line}", file=sys.stderr)


if __name__ == "__main__":
    main()
